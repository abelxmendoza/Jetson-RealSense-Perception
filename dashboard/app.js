"use strict";

const elements = Object.fromEntries([
  "file-input", "error-panel", "run-name", "source-badge", "state-card", "state-value",
  "state-subtitle", "nearest-value", "valid-value", "age-value", "time-value", "event-position",
  "timeline", "scrubber", "previous-button", "play-button", "next-button", "speed-select",
  "pass-count", "fail-count", "skip-count", "fault-reason", "expected-value", "outcome-value",
  "policy-value",
].map((id) => [id, document.getElementById(id)]));

let report = null;
let currentIndex = 0;
let timer = null;

function showError(message) {
  stopPlayback();
  elements["error-panel"].textContent = `Could not load recording\n${message}`;
  elements["error-panel"].hidden = false;
}

function clearError() {
  elements["error-panel"].hidden = true;
  elements["error-panel"].textContent = "";
}

function validateReport(candidate) {
  if (!candidate || candidate.report_type !== "bench_replay_report" || !Array.isArray(candidate.events)) {
    throw new Error("JSON reports must be generated by scripts/replay_bench.py");
  }
  if (!candidate.events.length) throw new Error("Replay report has no events");
  return candidate;
}

function loadReport(candidate) {
  report = validateReport(candidate);
  currentIndex = 0;
  clearError();
  elements["run-name"].textContent = report.recording.name;
  const source = report.recording.source || "unknown";
  elements["source-badge"].textContent = report.recording.source_label || source.toUpperCase();
  elements["source-badge"].className = `source-badge ${source}`;
  elements["pass-count"].textContent = report.summary.outcomes.PASS;
  elements["fail-count"].textContent = report.summary.outcomes.FAIL;
  elements["skip-count"].textContent = report.summary.outcomes.SKIP;
  elements.scrubber.max = Math.max(0, report.events.length - 1);
  elements.timeline.replaceChildren(...report.events.map((event, index) => {
    const marker = document.createElement("button");
    marker.type = "button";
    marker.className = event.status;
    marker.title = `${event.timestamp_s.toFixed(2)} s — ${event.status}`;
    marker.setAttribute("aria-label", marker.title);
    marker.addEventListener("click", () => selectEvent(index));
    return marker;
  }));
  selectEvent(0);
}

function selectEvent(index) {
  if (!report) return;
  currentIndex = Math.min(Math.max(0, index), report.events.length - 1);
  const event = report.events[currentIndex];
  const statusClass = event.status === "CLEAR" ? "status-clear" : event.status === "STOP" ? "status-stop" : "status-fault";
  elements["state-card"].className = `state-card panel ${statusClass}`;
  elements["state-value"].textContent = event.status;
  elements["state-subtitle"].textContent = event.fault_reason || (event.status === "STOP" ? "Obstacle inside stop distance" : "Depth sample satisfies policy");
  elements["nearest-value"].textContent = Number(event.nearest_distance_m).toFixed(2);
  elements["valid-value"].textContent = (Number(event.valid_depth_fraction) * 100).toFixed(1);
  elements["age-value"].textContent = Number(event.data_age_ms).toFixed(0);
  elements["time-value"].textContent = Number(event.timestamp_s).toFixed(2);
  elements["event-position"].textContent = `${currentIndex + 1} / ${report.events.length}`;
  elements.scrubber.value = currentIndex;
  elements["fault-reason"].textContent = event.fault_reason || "None";
  elements["expected-value"].textContent = event.expected_status || "Not supplied";
  elements["outcome-value"].textContent = event.outcome;
  const policy = report.policy;
  elements["policy-value"].textContent = `STOP ≤ ${policy.stop_distance_m} m · valid ≥ ${(policy.min_valid_depth_fraction * 100).toFixed(0)}% · age ≤ ${policy.max_data_age_ms} ms`;
  [...elements.timeline.children].forEach((marker, markerIndex) => marker.classList.toggle("active", markerIndex === currentIndex));
}

function stopPlayback() {
  if (timer) window.clearTimeout(timer);
  timer = null;
  elements["play-button"].textContent = "Play";
}

function scheduleNext() {
  if (!report || currentIndex >= report.events.length - 1) {
    stopPlayback();
    return;
  }
  const current = report.events[currentIndex];
  const next = report.events[currentIndex + 1];
  const delay = Math.max(80, ((next.timestamp_s - current.timestamp_s) * 1000) / Number(elements["speed-select"].value));
  timer = window.setTimeout(() => {
    selectEvent(currentIndex + 1);
    scheduleNext();
  }, delay);
}

elements["play-button"].addEventListener("click", () => {
  if (timer) return stopPlayback();
  if (report && currentIndex === report.events.length - 1) selectEvent(0);
  elements["play-button"].textContent = "Pause";
  scheduleNext();
});
elements["previous-button"].addEventListener("click", () => { stopPlayback(); selectEvent(currentIndex - 1); });
elements["next-button"].addEventListener("click", () => { stopPlayback(); selectEvent(currentIndex + 1); });
elements.scrubber.addEventListener("input", (event) => { stopPlayback(); selectEvent(Number(event.target.value)); });

elements["file-input"].addEventListener("change", async (event) => {
  const [file] = event.target.files;
  if (!file) return;
  clearError();
  try {
    const content = await file.text();
    if (file.name.toLowerCase().endsWith(".json")) {
      loadReport(JSON.parse(content));
    } else {
      const response = await fetch("/api/replay", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ name: file.name, content }),
      });
      const payload = await response.json();
      if (!response.ok) throw new Error(payload.error || `Server returned ${response.status}`);
      loadReport(payload);
    }
  } catch (error) {
    showError(error.message || String(error));
  } finally {
    event.target.value = "";
  }
});

fetch("/api/default")
  .then(async (response) => {
    const payload = await response.json();
    if (!response.ok) throw new Error(payload.error || `Server returned ${response.status}`);
    loadReport(payload);
  })
  .catch((error) => showError(error.message || String(error)));
